///! This Decoder consumes bytes from a reader interface and
///! decodes the bytes into frames of PCM data.
const std = @import("std");
const c = @import("c.zig");

const max_samples = c.max_samples_per_frame;
const max_frame_size = 1411;

pub const Decoder = @This();

output: [max_samples]i16,
input: [max_frame_size * 2]u8,
available: usize,
instance: c.Decoder,

/// Allocate space for the decoder and initialize the minimp3 instance.
pub fn init() Decoder {
    var dec: Decoder = .{
        .output = undefined,
        .input = undefined,
        .available = 0,
        .instance = undefined,
    };
    c.init(&dec.instance);
    return dec;
}

/// Reads bytes from rdr into an internal buffer until able to decode
/// a frame. If no frame is returned, then the caller has reached the
/// end of the MP3 stream.
pub fn nextFrame(self: *Decoder, rdr: anytype) !?Frame {
    // Read until the input buffer is full or EOF.
    self.available += try rdr.read(self.input[self.available..]);

    var info: c.Info = undefined;
    const num_frames = c.decode(
        &self.instance,
        &self.input,
        @intCast(self.available),
        &self.output,
        &info,
    );
    if (num_frames == 0) {
        return null;
    }

    // Remove the bytes consumed by the decoder.
    self.removeBytes(@intCast(info.frame_bytes));

    return .{
        .samples = self.output[0..@intCast(num_frames * info.channels)],
        .info = .{
            .frame_bytes = @intCast(info.frame_bytes),
            .frame_offset = @intCast(info.frame_offset),
            .channels = @intCast(info.channels),
            .hz = @intCast(info.hz),
            .layer = @intCast(info.layer),
            .bitrate = @intCast(info.bitrate_kbps),
        },
    };
}

/// Removes n bytes from the head of the input buffer after they've been consumed
/// by the decoder.
fn removeBytes(self: *Decoder, n: usize) void {
    std.mem.copyForwards(
        u8,
        &self.input,
        self.input[n..],
    );
    self.available -= n;
}

/// Contains information about a decoded frame.
const Info = struct {
    frame_bytes: usize,
    frame_offset: usize,
    channels: u2,
    hz: u32,
    layer: u2,
    bitrate: u32,
};

/// PCM data and information that applies to the frame it came from.
const Frame = struct {
    samples: []i16,
    info: Info,
};

